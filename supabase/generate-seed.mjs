#!/usr/bin/env node
/**
 * Regenerates supabase/seed.sql from the storefront catalogue in lib/products.ts
 * so the database seed can never drift from the demo data shipped in the app.
 *
 *   node supabase/generate-seed.mjs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { CATEGORIES, products } from "../lib/products.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const q = value =>
  value === null || value === undefined
    ? "null"
    : `'${String(value).replace(/'/g, "''")}'`;

const arr = values => `array[${values.map(q).join(", ")}]`;

const lines = [];
const out = sql => lines.push(sql);

out("-- Generated by supabase/generate-seed.mjs — do not edit by hand.");
out("-- Re-run `node supabase/generate-seed.mjs` after changing lib/products.ts.");
out("begin;");
out("");

out("/* categories */");
CATEGORIES.forEach((category, index) => {
  out(
    `insert into public.categories (slug, label, position) values (${q(category.slug ?? category.key)}, ${q(category.label)}, ${index}) on conflict (slug) do nothing;`
  );
});
out("");

out("/* products */");
products.forEach((product, index) => {
  const description = arr(product.description);
  const specs = JSON.stringify(
    product.specs.map(([name, value]) => ({ name, value }))
  ).replace(/'/g, "''");
  out(
    [
      `insert into public.products (slug, title, category_id, short_description, description, specs, price_cents, compare_at_price_cents, badge, rating, reviews, is_active, is_featured)`,
      `select ${q(product.slug)}, ${q(product.title)}, c.id, ${q(product.short)}, ${description}, '${specs}'::jsonb, ` +
        `${Math.round(product.price * 100)}, ` +
        `${product.oldPrice ? Math.round(product.oldPrice * 100) : "null"}, ` +
        `${q(product.badge ?? null)}, ${product.rating}, ${product.reviews}, true, ${index < 4}`,
      `from public.categories c where c.slug = ${q(product.category)}`,
      `on conflict (slug) do nothing;`
    ].join("\n")
  );
});
out("");

out("/* product images */");
products.forEach(product => {
  out(
    `insert into public.product_images (product_id, kind, path, alt) select p.id, 'primary', '/images/${product.image}', ${q(product.title)} from public.products p where p.slug = ${q(product.slug)} on conflict (product_id, kind) do nothing;`
  );
  out(
    `insert into public.product_images (product_id, kind, path, alt) select p.id, 'hover', '/images/${product.hover}', ${q(product.title)} from public.products p where p.slug = ${q(product.slug)} on conflict (product_id, kind) do nothing;`
  );
});
out("");

out("/* inventory */");
products.forEach(product => {
  out(
    `insert into public.inventory (product_id, variant_id, on_hand) select p.id, null, ${product.stock} from public.products p where p.slug = ${q(product.slug)} on conflict do nothing;`
  );
});
out("");

out("/* example variants (optional — delete freely) */");
out(
  `insert into public.product_variants (product_id, sku, name, options, price_cents) select p.id, 'IP13M-128-PINK', '128GB / Pink', '{"storage":"128GB","colour":"Pink"}'::jsonb, null from public.products p where p.slug = 'apple-iphone-13-mini-128gb-pink' on conflict (sku) do nothing;`
);
out(
  `insert into public.product_variants (product_id, sku, name, options, price_cents) select p.id, 'IP13M-256-PINK', '256GB / Pink', '{"storage":"256GB","colour":"Pink"}'::jsonb, 19900 from public.products p where p.slug = 'apple-iphone-13-mini-128gb-pink' on conflict (sku) do nothing;`
);
out("");

out("/* store settings */");
out(
  `insert into public.store_settings (id, store_name, currency, standard_shipping_cents, express_shipping_cents, checkout_enabled) values (true, 'Racine IT', 'USD', 0, 1500, true) on conflict (id) do nothing;`
);
out("");
out("commit;");

const target = join(root, "supabase", "seed.sql");
writeFileSync(target, `${lines.join("\n")}\n`);
console.log(`wrote ${target} (${products.length} products)`);
